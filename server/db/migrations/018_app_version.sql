--
-- Нужно администратору, чтобы понять, когда все перешли на новую версию:
-- например, прежде чем закрывать репозиторий, откуда старые версии берут
-- обновления. Приложение присылает версию в заголовке каждого запроса, сервер
-- запоминает её у учётки и время последнего обращения. Больше ничего о работе
-- человека не хранится.
--
-- Пусто — версия старше той, что научилась себя называть.

ALTER TABLE app_user
    ADD COLUMN IF NOT EXISTS app_version  TEXT,
    ADD COLUMN IF NOT EXISTS app_platform TEXT,
    ADD COLUMN IF NOT EXISTS app_seen_at  TIMESTAMPTZ;
