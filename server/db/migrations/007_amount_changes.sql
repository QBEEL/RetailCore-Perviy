-- Пометка «сумму изменил человек».
--
-- Менеджер или администратор правит сумму оплаты — и в календаре это должно
-- быть видно: день стал тяжелее или легче не потому, что так пришло из 1С.
-- Журнал изменений ответить на это не может: он хранит новое значение, а не
-- прежнее, и читать его на каждый день календаря — семь тысяч строк впустую.
--
-- `amount_before` — сумма до первой ручной правки. Вторая правка её не
-- перезаписывает: важно, от чего ушли, а не предпоследний шаг. Вернули сумму
-- к прежней — пометка снимается, менять больше нечего.
--
-- Импорт 1С правку человека не затирает, пока в 1С сумма та же, что была до
-- правки. Пришла новая сумма из 1С — она новее правки, и пометка снимается.
ALTER TABLE payment ADD COLUMN IF NOT EXISTS amount_before NUMERIC(16,2);
ALTER TABLE payment ADD COLUMN IF NOT EXISTS amount_changed_by BIGINT
    REFERENCES app_user(id) ON DELETE SET NULL;
ALTER TABLE payment ADD COLUMN IF NOT EXISTS amount_changed_at TIMESTAMPTZ;
