-- Версия входа на учётке.
--
-- В токене теперь лежит версия учётки, и сервер сверяет её на каждом запросе.
-- Версия растёт при смене пароля, его сбросе администратором и отключении
-- учётки: выданные до этого входы заканчиваются, и пароль спрашивается заново.
--
-- Токены, выданные до миграции, версии не содержат и читаются как нулевая:
-- сразу после обновления никого не выбросит из программы.

ALTER TABLE app_user
    ADD COLUMN IF NOT EXISTS token_version INTEGER NOT NULL DEFAULT 0;
