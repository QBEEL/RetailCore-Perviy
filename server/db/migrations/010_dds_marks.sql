-- Цвет и метка статьи ДДС.
--
-- Администратор отмечает статью цветом и короткой меткой: оплаты с этой статьёй
-- в таблице и календаре получают цветной кружок, подсветку строки и заметку
-- рядом. Так, «Маркетинг (ГПН)» и «Маркетинг (Адвент)» можно сделать розовыми с
-- меткой «Маркетинг» и видеть весь маркетинг с первого взгляда.
--
-- Хранится в справочнике, а не в оплатах: смена цвета сразу действует на все
-- оплаты статьи, перекрашивать тысячи строк не нужно.
--
-- color — «#RRGGBB» или пустая строка (без цвета); note — подпись, может быть
-- пустой: тогда виден только кружок.

ALTER TABLE dds_item ADD COLUMN IF NOT EXISTS color TEXT NOT NULL DEFAULT '';
ALTER TABLE dds_item ADD COLUMN IF NOT EXISTS note  TEXT NOT NULL DEFAULT '';
