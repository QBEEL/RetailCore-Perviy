-- Оплата «вместо другого поставщика».

-- Бывает, что намеченную оплату одному поставщику пускают на другого: деньги те
-- же, а получатель другой. Без отметки это выглядит как две несвязанные истории
-- — недобор у одного и незапланированная оплата у второго.
--
-- Отметку ставит тот, кто заводит оплату: в поле лежит название поставщика, на
-- место которого платят. Выгрузка 1С поля не содержит и его не затирает.
-- Хранится название, а не номер, по той же причине, что и `recipient`: у
-- поставщика из 1С карточки в базе может не быть.

ALTER TABLE payment ADD COLUMN IF NOT EXISTS instead_of TEXT NOT NULL DEFAULT '';
