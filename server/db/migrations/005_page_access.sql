-- Разделы приложения, закрытые у учётной записи.
--
-- Появилось из простого запроса: маркировкой занимаются двое, а вкладка висит
-- у всех восемнадцати — и у тех, кто ни разу не вставлял носитель с ключом.
--
-- Хранится список закрытых, а не открытых разделов. С открытыми каждая версия
-- приложения с новой вкладкой начиналась бы с обхода всех учёток, чтобы выдать
-- право на то, что вчера работало без спроса; забытая учётка при этом молча
-- теряла бы раздел. Закрытый список ведёт себя иначе: новое доступно всем, а
-- запись здесь — это осознанное «этому человеку не нужно».
--
-- Справочника разделов на сервере нет намеренно. Коды задаёт приложение, и
-- копия их списка здесь означала бы миграцию на каждую новую вкладку — ради
-- проверки, которая ничего не защищает: право на данные общей базы считается
-- отдельно и к меню отношения не имеет.
CREATE TABLE IF NOT EXISTS user_page_denied (
    user_id   BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    page_code TEXT   NOT NULL,
    PRIMARY KEY (user_id, page_code)
);
