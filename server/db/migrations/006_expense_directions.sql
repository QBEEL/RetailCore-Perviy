-- Направления расходов: Маркетинг, Налоги, Аренда.
--
-- Отбор оплат по направлению делит выборку на Beauty, Fashion и «остальные»,
-- и в «остальных» лежат вперемешку аренда магазинов, налоги и маркетинг. По
-- операции 1С их не отличить: аренду магазинов и маркетинг 1С проводит той же
-- «Оплатой поставщику», что и товар. Поэтому это такие же направления
-- поставщика, которые ставит администратор.
--
-- Но это направления расхода, а не отдела. Менеджеру их назначать нельзя:
-- направление учётки — признак категорийного менеджера, и «Налоги» в нём
-- превратили бы бухгалтера в того, кому предлагают закрепление поставщиков.
-- Отсюда `for_people`: справочник общий, а в учётку идут только отделы.

ALTER TABLE direction
    ADD COLUMN IF NOT EXISTS for_people BOOLEAN NOT NULL DEFAULT TRUE;

INSERT INTO direction (code, title, sort_order, for_people) VALUES
    ('marketing', 'Маркетинг', 3, FALSE),
    ('taxes',     'Налоги',    4, FALSE),
    ('rent',      'Аренда',    5, FALSE)
ON CONFLICT (code) DO NOTHING;

-- Если такие направления кто-то уже успел назначить людям — снять: иначе
-- пересчёт закреплений разнёс бы их по всем поставщикам этого человека.
DELETE FROM user_direction ud
 USING direction d
 WHERE d.id = ud.direction_id AND NOT d.for_people;
