-- Статья ДДС оплаты.
--
-- Статья указывает, куда платёж относится в отчёте о движении денег: «Оплата
-- поставщику (бьюти)», «Аренда», «Услуги связи». Выгрузка 1С её не содержит,
-- поэтому заполняет статью тот, кто заводит оплату, а импорт её не трогает.
--
-- Справочник общий: администратор добавляет статьи в приложении, и они сразу
-- видны всем. Начальное наполнение — перечень из «Статьи ДДС.xlsx».
--
-- В оплате хранится название, а не номер: так же, как `operation`. Название
-- статьи не переименовывается, а справочник нужен для выбора и проверки при
-- записи, и связывать каждую из тысяч оплат внешним ключом ради этого незачем.
-- Уникальность — без учёта регистра: «аренда» и «Аренда» — одна статья.

CREATE TABLE IF NOT EXISTS dds_item (
    id         SERIAL      PRIMARY KEY,
    title      TEXT        NOT NULL CHECK (title = btrim(title) AND title <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT      REFERENCES app_user(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS dds_item_title ON dds_item (lower(title));

