-- Справочник брендов для заявок Торг-2.
--
-- Склад вводит бренд руками, и один и тот же писали по-разному: «Biorepair»,
-- «BIOREPAIR», «Bio repair». Справочник нужен для подсказки при наборе: человек
-- начинает печатать, программа предлагает написание из списка, и бренд в заявках
-- становится единым. Заявка по-прежнему хранит бренд текстом, а не ссылкой:
-- нового бренда на приёмке никто ждать не будет, а старые заявки не должны
-- менять написание, если бренд потом переименуют.
--
-- Начальный список — 668 брендов из файла «Бренды (Все).xlsx», который вёл склад.
-- Дальше любой может добавить свой прямо из заявки.

CREATE TABLE IF NOT EXISTS claim_brand (
    id         BIGSERIAL PRIMARY KEY,
    name       TEXT        NOT NULL,
    -- Ключ сравнения: без регистра, лишних пробелов и «ё». По нему бренд нельзя
    -- завести дважды под разным написанием.
    name_key   TEXT        NOT NULL UNIQUE,
    added_by   BIGINT      REFERENCES app_user(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

