-- Пометка «не было запланировано».
--
-- Заявку на оплату завели в 1С, а в приложении плана на неё не было: ни плана
-- менеджера, ни ручной записи на этого получателя и этот день. Заявка из такой
-- выгрузки получает пометку при создании, и дальше импорт её не трогает —
-- повторная выгрузка той же заявки пометку не снимает и не ставит заново.
--
-- Пометка ставится, только если база уже знала прошлые выгрузки: первая
-- выгрузка приносит всю историю разом, и «не планировалось» оказалось бы у
-- каждой заявки. У уже лежащих в базе оплат она остаётся пустой — задним числом
-- отличить незапланированное от запланированного нечем.

ALTER TABLE payment ADD COLUMN IF NOT EXISTS unplanned BOOLEAN NOT NULL DEFAULT FALSE;
