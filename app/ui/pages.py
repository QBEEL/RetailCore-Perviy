"""Разделы приложения: порядок, названия, иконки, сочетания клавиш и доступ.

Список вынесен из главного окна, потому что нужен ещё и карточке учётной
записи: администратор отмечает там, какие разделы человеку показывать. Держать
два перечня — значит однажды закрыть раздел, которого в меню уже нет.

Право на раздел хранится списком **закрытых** кодов, а не открытых. Новый
раздел так появляется у всех сам: иначе каждая версия с новой вкладкой
начиналась бы с обхода двадцати учёток, которым надо выдать доступ к тому, что
вчера работало без спроса.

Это настройка рабочего места, а не защита. Доступ к данным общей базы считает
сервер и присылает готовым (`editable`, отказ для не-администратора), а
«Маркировка» ходит в «Честный ЗНАК» по личному сертификату и о приложении не
знает вовсе. Здесь решается одно: не показывать человеку то, чем он не
пользуется.
"""
from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Page:
    """Раздел бокового меню."""

    # Код хранится в правах на сервере и переживает переименования: название
    # раздела в меню меняется свободно, а вот смена кода молча вернула бы
    # закрытый раздел всем, кому его закрыли.
    code: str
    title: str
    icon: str
    shortcut: str
    # Может ли администратор закрыть раздел. См. ниже, почему таких два.
    managed: bool = True


PAGES = (
    Page("match", "Сопоставление", "match", "Ctrl+1"),
    Page("order", "Заказ", "order", "Ctrl+2"),
    Page("price", "Быстрая смена цен", "price", "Ctrl+3"),
    Page("payments", "Оплаты", "payments", "Ctrl+4"),
    Page("suppliers", "Поставщики", "suppliers", "Ctrl+5"),
    # Сочетание буквенное, а не следующее по счёту: ряд Ctrl+1…Ctrl+0 занят
    # целиком, и вставка в его середину сдвинула бы все привычные сочетания
    # ради одного нового раздела.
    Page("marking", "Маркировка", "marking", "Ctrl+M"),
    Page("reports", "Отчётность", "report", "Ctrl+6"),
    Page("catalog", "Каталог", "catalog", "Ctrl+7"),
    Page("history", "История данных", "history", "Ctrl+8"),
    # Настройки не закрываются: там адрес сервера, профили поставщиков и
    # соответствие колонок. Человек, которому закрыли настройки, не починит
    # даже собственное подключение и пойдёт за этим к администратору.
    Page("settings", "Настройки", "settings", "Ctrl+9", managed=False),
    # Администрирование управляется признаком администратора. Второй механизм
    # для того же самого рано или поздно разошёлся бы с первым — и кто-то
    # остался бы с правами, но без раздела, или наоборот.
    # Последняя страница, поэтому Ctrl+0: Ctrl+10 не существует, а разрывать
    # ряд ради неё пришлось бы во всех остальных сочетаниях.
    Page("admin", "Администрирование", "admin", "Ctrl+0", managed=False),
)

# Разделы, которые администратор вправе закрыть, — для карточки учётной записи.
MANAGED = tuple(page for page in PAGES if page.managed)


@dataclass(frozen=True, slots=True)
class Part:
    """Вкладка внутри раздела, которую можно закрыть отдельно от него.

    Нужна там, где в одном разделе собраны отчёты для разных людей: аналитику
    по чекам с выручкой и прибылью видеть всем незачем, а отчёт поставщику в
    том же разделе нужен каждому менеджеру. Закрыть раздел целиком значило бы
    отнять и то, и другое.
    """

    code: str
    title: str
    page: str


# Порядок — как вкладки стоят в разделе: по нему они и прячутся.
PARTS = (
    Part("reports.supplier", "Отчёт поставщику", "reports"),
    Part("reports.ledger", "Ведомость по складам", "reports"),
    Part("reports.receipts", "Аналитика по чекам", "reports"),
)


def parts_of(page: str) -> tuple[Part, ...]:
    return tuple(part for part in PARTS if part.page == page)


def index_of(code: str) -> int:
    """Номер раздела в стопке страниц. Порядок здесь и там один."""
    for index, page in enumerate(PAGES):
        if page.code == code:
            return index
    raise KeyError(f"раздел {code} не описан")


def describe(denied: Iterable[str]) -> str:
    """Чего человек не видит — одной строкой для таблицы учётных записей.

    Пусто, когда открыто всё: такова обычная учётка, и писать в каждой её
    строке «доступны все разделы» значило бы зашумить таблицу ради исключений.
    """
    closed = set(denied)
    titles = [page.title for page in MANAGED if page.code in closed]
    # Вкладки закрытого раздела не перечисляются: они и так закрыты вместе с
    # ним, а список ради них вырос бы втрое.
    titles += [part.title for part in PARTS
               if part.code in closed and part.page not in closed]
    return "закрыто: " + ", ".join(titles) if titles else ""
