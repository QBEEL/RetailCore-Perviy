def stale(today: date | None = None) -> bool:
    """Не пора ли перепроверить таблицу: давно собрана."""
    return (today or date.today()) - AS_OF > STALE_AFTER


def upcoming(today: date | None = None,
             within: int = SOON_DAYS) -> list[tuple[GroupDeadlines, Milestone]]:
    """Даты, которые наступят в ближайшие `within` дней, по возрастанию."""
    now = today or date.today()
    limit = now + timedelta(days=within)
    found = [(group, item) for group in DEADLINES for item in group.milestones
             if now <= item.day <= limit]
    return sorted(found, key=lambda pair: pair[1].day)


def short_date(day: date) -> str:
    months = ("января", "февраля", "марта", "апреля", "мая", "июня", "июля",
              "августа", "сентября", "октября", "ноября", "декабря")
    return f"{day.day} {months[day.month - 1]}"


def soon_caption(today: date | None = None) -> str:
    """Подпись для кнопки: ближайшая дата, если она скоро. Иначе пусто."""
    found = upcoming(today)
    if not found:
        return ""
    group, item = found[0]
    return f"скоро {short_date(item.day)}: {group.title}"


def as_html(today: date | None = None, *, muted: str = "#64748b",
            accent: str = "#d97706") -> str:
    """Памятка готовым текстом для окна. Прошедшие даты приглушены, будущие — крупно."""
    now = today or date.today()
    parts: list[str] = []
    if stale(now):
        parts.append(
            f'<p style="color:{accent}"><b>Таблица собрана {AS_OF:%d.%m.%Y} и могла '
            "устареть — сверьтесь с честныйзнак.рф.</b></p>")
    for group in DEADLINES:
        parts.append(f"<h4 style='margin:10px 0 2px 0'>{escape(group.title)}</h4>")
        parts.append(f"<div>{escape(group.status)}</div>")
        if group.milestones:
            parts.append("<ul style='margin:2px 0 0 0'>")
            for item in sorted(group.milestones, key=lambda entry: entry.day):
                text = f"<b>{item.day:%d.%m.%Y}</b> — {escape(item.text)}"
                if item.day < now:
                    parts.append(f"<li style='color:{muted}'>{text}</li>")
                else:
                    left = (item.day - now).days
                    when = "сегодня" if left == 0 else f"через {left} дн."
                    parts.append(f"<li style='color:{accent}'>{text} <b>({when})</b></li>")
            parts.append("</ul>")
        if group.note:
            parts.append(f"<div style='color:{muted}'><i>{escape(group.note)}</i></div>")
    parts.append(
        f"<p style='color:{muted}'>Справка по открытым источникам на {AS_OF:%d.%m.%Y}, "
        "не официальный документ. Источники: " + "; ".join(map(escape, SOURCES)) +
        ". Спорный случай — на честныйзнак.рф.</p>")
    return "".join(parts)
