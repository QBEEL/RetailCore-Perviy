@dataclass(frozen=True, slots=True)
class DdsItem:
    """Статья справочника с пометкой, если её задал администратор."""

    title: str
    id: int = 0
    # «#RRGGBB» или пусто — без цвета.
    color: str = ""
    # Короткая подпись рядом с оплатой: «Маркетинг».
    note: str = ""

    @property
    def marked(self) -> bool:
        return bool(self.color or self.note)


