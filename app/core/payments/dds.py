def clean(title: str) -> str:
    """Название без лишних пробелов, в том числе внутри: «Аренда  офиса»."""
    return " ".join(title.split())


def default_item(directions: tuple[str, ...] | None = None) -> str:
    """Статья по умолчанию для менеджера с такими направлениями.

    Если ведёт оба отдела, берётся первый по порядку справочника — Beauty:
    поставить сразу обе нельзя, а угадать по получателю на этом шаге нечем.
    Менеджеру без направления умолчание не нужно — он выбирает сам.
    """
    chosen = transport.session.directions if directions is None else directions
    return next((DEFAULT_BY_DIRECTION[code] for code in chosen
                 if code in DEFAULT_BY_DIRECTION), "")


# Пометки по названию статьи — кэш последнего чтения справочника. Таблица
# оплат спрашивает пометку у каждой строки, и сервер на каждую строку
# не опрашивается: справочник читается вместе с оплатами, один раз.
_marks: dict[str, DdsItem] = {}


def catalog() -> list[DdsItem]:
    """Справочник статей по алфавиту, вместе с цветами и метками.

    Сервер спрашивается всегда, когда выполнен вход, — даже если администратор
    сидит на своей локальной базе: справочник общий. Сервер без этого адреса
    или недоступный даёт встроенный список без пометок, а не пустой выбор.
    Прочитанное запоминается для `mark_of`.
    """
    found: list[DdsItem] = []
    if transport.session.active:
        try:
            rows = transport.get("/api/dds-items")
        except transport.ServerError:
            rows = None
        found = [DdsItem(title=row["title"], id=int(row.get("id") or 0),
                         color=row.get("color") or "", note=row.get("note") or "")
                 for row in rows or []]
    if not found:
        found = [DdsItem(title=title) for title in BUILTIN_ITEMS]
    _marks.clear()
    _marks.update({item.title: item for item in found if item.marked})
    return found


def items() -> list[str]:
    """Названия статей для выбора, по алфавиту."""
    return [item.title for item in catalog()]


def mark_of(title: str) -> DdsItem | None:
    """Пометка статьи или None, если её не отмечали.

    Работает по кэшу: справочник читается при загрузке оплат, а не здесь.
    """
    return _marks.get(title) if title else None


def add(title: str) -> str:
    """Добавляет статью (только администратор). Возвращает сохранённое название."""
    return transport.post("/api/dds-items", {"title": clean(title)})["title"]


def set_mark(ids: list[int], color: str, note: str) -> int:
    """Задаёт цвет и метку выбранным статьям (только администратор).

    Пустые значения снимают пометку. Возвращает число обновлённых статей.
    """
    try:
        rows = transport.patch("/api/dds-items",
                               {"ids": ids, "color": color, "note": " ".join(note.split())})
    except transport.ServerError as error:
        if error.status in (404, 405):
            # Сервер до цветов знает чтение и добавление статей, а правку — нет.
            # Сырое «Method Not Allowed» человеку ничего не говорит.
            raise transport.ServerError(
                "Серверная часть не обновлена: цвета статей ей ещё неизвестны. "
                "Обновите сервер оплат", error.status) from error
        raise
    return len(rows or [])
