"""Доверенные корневые сертификаты для HTTPS.

Корни берутся из двух источников сразу: системного хранилища и набора `certifi`,
который PyInstaller кладёт внутрь сборки. Ни одного из них по отдельности не
хватает.

Системного не хватает потому, что Let's Encrypt меняет корни быстрее, чем их
разносит обновление Windows. В сентябре 2026 сертификат сервера стал выдаваться
через новый промежуточный YE1 с путём до «Root YE», кросс-подписанного ISRG Root
X2, и на машинах без свежего хранилища проверка перестала проходить: у одного
человека программа работала, у другого — «Сервер оплат недоступен». Набор из
сборки такие корни приносит с собой, не дожидаясь обновления системы.

Набора `certifi` не хватает потому, что он знает только публичные центры. В сети
с антивирусом или прокси, разбирающим HTTPS, сервер предъявляет сертификат
локального центра — он есть в системном хранилище и больше нигде.

На macOS моста к системному хранилищу нет вовсе: `ssl` читает пути, зашитые в
OpenSSL при сборке Python, а в собранном приложении на чужой машине их не
существует. Там список системных корней просто пуст, и работает один `certifi`.
"""
from __future__ import annotations

import ssl


def _build() -> ssl.SSLContext:
    # Системные корни: их даёт сам `create_default_context`.
    context = ssl.create_default_context()
    try:
        import certifi
    except ImportError:
        # Проверку сертификата не отключаем даже здесь: честная ошибка лучше
        # тихого обхода TLS, при котором токен уйдёт кому угодно.
        return context
    try:
        # Поверх системных, а не вместо них: добавление корней ничего не
        # отменяет, и сертификат локального центра продолжит проходить.
        context.load_verify_locations(cafile=certifi.where())
    except (OSError, ssl.SSLError):
        # Набор не прочитался — остаёмся с системными корнями. Это хуже, чем с
        # обоими, но лучше, чем без связи вообще.
        pass
    return context


context = _build()
